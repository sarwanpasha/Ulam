"""Finite trees: enumeration of free trees, distances, and the double spiders used in
the edge-local lower bound (4) of the paper.

A tree is stored as a dict {vertex: sorted list of neighbours} with vertices 0..k-1.
"""

from collections import deque
from itertools import combinations


def make_tree(edges):
    adj = {}
    for u, v in edges:
        adj.setdefault(u, []).append(v)
        adj.setdefault(v, []).append(u)
    return {u: sorted(nb) for u, nb in sorted(adj.items())}


def edges_of(tree):
    return [(u, v) for u in tree for v in tree[u] if u < v]


def bfs_distances(tree, root):
    dist = {root: 0}
    q = deque([root])
    while q:
        u = q.popleft()
        for v in tree[u]:
            if v not in dist:
                dist[v] = dist[u] + 1
                q.append(v)
    return dist


def all_distances(tree):
    return {u: bfs_distances(tree, u) for u in tree}


def diameter(tree):
    return max(max(d.values()) for d in all_distances(tree).values())


def max_degree(tree):
    return max(len(nb) for nb in tree.values())


def centers(tree):
    """The one or two central vertices (by repeatedly stripping leaves)."""
    deg = {u: len(nb) for u, nb in tree.items()}
    alive = set(tree)
    leaves = [u for u in alive if deg[u] <= 1]
    while len(alive) > 2:
        new = []
        for u in leaves:
            alive.discard(u)
            for v in tree[u]:
                if v in alive:
                    deg[v] -= 1
                    if deg[v] == 1:
                        new.append(v)
        leaves = new
    return sorted(alive)


def _rooted_canon(tree, u, parent):
    subs = sorted(_rooted_canon(tree, v, u) for v in tree[u] if v != parent)
    return "(" + "".join(subs) + ")"


def canonical_form(tree):
    """Canonical string of a free tree (AHU encoding rooted at the center or at the
    smaller of the two encodings for a central edge)."""
    c = centers(tree)
    if len(c) == 1:
        return _rooted_canon(tree, c[0], None)
    a, b = c
    s1 = _rooted_canon(tree, a, b)
    s2 = _rooted_canon(tree, b, a)
    return "E" + "".join(sorted([s1, s2]))


def free_trees(k):
    """All free trees with k vertices, each as a dict, generated by attaching one leaf
    to every vertex of every tree with k-1 vertices and removing duplicates."""
    if k == 1:
        return [{0: []}]
    out = {}
    for t in free_trees(k - 1):
        for u in t:
            new = {v: list(nb) for v, nb in t.items()}
            new[u].append(k - 1)
            new[k - 1] = [u]
            new = {v: sorted(nb) for v, nb in new.items()}
            key = canonical_form(new)
            if key not in out:
                out[key] = new
    return list(out.values())


def relabel(tree, order):
    """Relabel the vertices of tree so that order[i] becomes vertex i."""
    pos = {v: i for i, v in enumerate(order)}
    return {pos[u]: sorted(pos[v] for v in tree[u]) for u in order}


def induced_subtree(tree, verts):
    """The subtree induced by a connected vertex set, relabelled to 0..|verts|-1."""
    verts = sorted(verts)
    S = set(verts)
    sub = {u: [v for v in tree[u] if v in S] for u in verts}
    return relabel(sub, verts)


def longest_path_from(tree, start, forbidden):
    """Vertices of a longest path that starts at start and avoids the vertex forbidden
    (a longest path into the branch of start away from forbidden)."""
    best = [start]

    def dfs(u, parent, path):
        nonlocal best
        if len(path) > len(best):
            best = list(path)
        for v in tree[u]:
            if v != parent and v != forbidden:
                path.append(v)
                dfs(v, u, path)
                path.pop()

    dfs(start, forbidden, [start])
    return best


def double_spider(tree, u, v):
    """The double spider DS_uv: the edge uv together with a longest path into every
    branch hanging off u (away from v) and off v (away from u).  Returned as a tree on
    0..k-1 together with the list of original vertices."""
    verts = {u, v}
    for w in tree[u]:
        if w != v:
            verts.update(longest_path_from(tree, w, u))
    for w in tree[v]:
        if w != u:
            verts.update(longest_path_from(tree, w, v))
    return induced_subtree(tree, verts), sorted(verts)


def spider(d, l):
    """The spider S(d, l) as a tree on 1 + d*l vertices; vertex 0 is the center."""
    edges = []
    nxt = 1
    for _ in range(d):
        prev = 0
        for _ in range(l):
            edges.append((prev, nxt))
            prev = nxt
            nxt += 1
    return make_tree(edges)
